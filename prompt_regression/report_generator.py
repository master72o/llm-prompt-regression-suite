"""
Report Generator for LLM Prompt Regression Suite.
"""

import os
import json
import pandas as pd
from typing import Dict, Any, List
from prompt_regression.schema import RegressionSuiteReport, RegressionType


class ReportGenerator:
    """Generates Markdown CI reports and exports JSON/CSV results."""

    @staticmethod
    def generate_markdown_report(report: RegressionSuiteReport, output_path: str) -> str:
        os.makedirs(os.path.dirname(output_path), exist_ok=True)

        status_badge = "🟢 PASSED" if report.ci_passed else "🔴 FAILED (QUALITY GATE VIOLATION)"

        reg_rows = []
        for r in report.regressions:
            t_str = r.regression_type.value if isinstance(r.regression_type, RegressionType) else str(r.regression_type)
            crit_str = "⚠️ YES" if r.is_critical else "NO"
            reg_rows.append(
                f"| `{r.test_id}` | `{t_str}` | {r.score_delta:+.4f} | {r.baseline_result.overall_score:.4f} | {r.candidate_result.overall_score:.4f} | {crit_str} |"
            )

        reg_table = "\n".join(reg_rows) if reg_rows else "| None | None | 0.0000 | N/A | N/A | NO |"

        content = f"""# LLM Prompt & Model Version Regression Report

## CI Quality Gate Decision: {status_badge}

---

## Executive Summary

- **Baseline Version**: `{report.baseline_version}`
- **Candidate Version**: `{report.candidate_version}`
- **Total Test Cases**: `{report.total_tests}`
- **Quality Gate Threshold**: `{report.quality_gate_threshold*100:.1f}%`

---

## Key Performance Comparison

| Metric | Baseline (`{report.baseline_version}`) | Candidate (`{report.candidate_version}`) | Delta ($\Delta$) | Status |
| :--- | :--- | :--- | :--- | :--- |
| **Pass Rate** | `{report.baseline_pass_rate*100:.1f}%` | `{report.candidate_pass_rate*100:.1f}%` | `{((report.candidate_pass_rate - report.baseline_pass_rate)*100):+.1f}%` | {"🟢 OK" if report.candidate_pass_rate >= report.quality_gate_threshold else "🔴 FAIL"} |
| **Mean Score** | `{report.baseline_mean_score:.4f}` | `{report.candidate_mean_score:.4f}` | `{(report.candidate_mean_score - report.baseline_mean_score):+.4f}` | {"🟢 OK" if (report.candidate_mean_score - report.baseline_mean_score) >= -0.05 else "🔴 REGRESSION"} |
| **Critical Failures** | `0` | `{sum(1 for r in report.regressions if r.is_critical)}` | — | {"🟢 ZERO" if sum(1 for r in report.regressions if r.is_critical) == 0 else "🔴 CRITICAL BREACH"} |

---

## Detected Regressions Table

| Test ID | Regression Type | Score Delta | Baseline Score | Candidate Score | Critical? |
| :--- | :--- | :--- | :--- | :--- | :--- |
{reg_table}

---

## CI/CD Deployment Recommendation

{"✅ **APPROVED FOR DEPLOYMENT**: Candidate prompt version meets all performance, format, and safety thresholds." if report.ci_passed else "❌ **BLOCK DEPLOYMENT**: Candidate prompt version introduces critical quality or formatting regressions."}

---

## Visual Artifacts
- Pass Rate & Quality Gate: `reports/figures/pass_rate_comparison.png`
- Test Delta Breakdown: `reports/figures/metric_delta_breakdown.png`
- Regression Type Distribution: `reports/figures/regression_type_distribution.png`

---
*Report auto-generated by LLM Prompt Regression Suite v1.0.0*
"""

        with open(output_path, "w", encoding="utf-8") as f:
            f.write(content)

        return content

    @staticmethod
    def export_results(report: RegressionSuiteReport, output_dir: str):
        os.makedirs(output_dir, exist_ok=True)

        summary_json = {
            "baseline_version": report.baseline_version,
            "candidate_version": report.candidate_version,
            "total_tests": report.total_tests,
            "baseline_pass_rate": report.baseline_pass_rate,
            "candidate_pass_rate": report.candidate_pass_rate,
            "baseline_mean_score": report.baseline_mean_score,
            "candidate_mean_score": report.candidate_mean_score,
            "ci_passed": report.ci_passed,
            "regressions": [r.to_dict() for r in report.regressions],
        }

        json_path = os.path.join(output_dir, "regression_summary.json")
        with open(json_path, "w", encoding="utf-8") as f:
            json.dump(summary_json, f, indent=2)

        csv_rows = []
        for r in report.regressions:
            csv_rows.append({
                "test_id": r.test_id,
                "regression_type": r.regression_type.value if isinstance(r.regression_type, RegressionType) else str(r.regression_type),
                "score_delta": r.score_delta,
                "is_critical": r.is_critical,
                "baseline_passed": r.baseline_result.passed,
                "candidate_passed": r.candidate_result.passed,
                "baseline_score": r.baseline_result.overall_score,
                "candidate_score": r.candidate_result.overall_score,
            })

        df = pd.DataFrame(csv_rows)
        csv_path = os.path.join(output_dir, "regressions_detail.csv")
        df.to_csv(csv_path, index=False)
